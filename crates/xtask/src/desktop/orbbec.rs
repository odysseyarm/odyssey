//! Stages what the MSI needs for one build variant.
//!
//! Writes `<stage>/orbbec.wxs`, the `WiX` fragment the `wix` section of
//! crates/odyssey-desktop/Cargo.toml points at, and for the full variant also the files it
//! installs. `cargo-packager` runs afterwards with
//! `CARGO_PACKAGER_ODYSSEY_MSI_VARIANT=<variant>` and
//! `CARGO_PACKAGER_ODYSSEY_ORBBEC_STAGE=<stage>` (absolute; the template reads EULA.rtf from it).
//!
//! online   A fragment with a hidden, empty feature. The installer carries nothing; the
//!          app downloads the SDK itself (see `src/sdk_install`).
//! full     Downloads the SDK release in orbbec-sdk.json, checks its sha256, unpacks the
//!          listed files into `<stage>/orbbec-sdk`, fetches the EULA (checked too), turns
//!          it into the installer's licence page, and writes a fragment that installs it
//!          all as an optional feature on by default.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;
use std::fs;
use std::io::{Cursor, Read as _};
use std::path::{Component, Path, PathBuf};
use std::time::Duration;

use eros::Context as _;
use serde::Deserialize;
use sha1::Sha1;
use sha2::{Digest as _, Sha256};

use super::{DIR, Variant};
use crate::cmd;

const PIN_FILE: &str = "orbbec-sdk.json";

/// Component GUIDs must stay the same from one release to the next or an upgrade
/// treats every file as new. Deriving them from the install path (inside this fixed
/// namespace) makes them stable. Never change this value.
const GUID_NAMESPACE: &str = "5a1c0f4e-2f0f-4a52-9d57-6b3d2e0c2b91";

/// `WiX` rejects longer identifiers.
const WIX_ID_MAX: usize = 72;

const FEATURE_TITLE: &str = "Orbbec camera support";
const FEATURE_DESCRIPTION: &str = "Orbbec's camera software, needed to calibrate a screen with an Orbbec depth camera. Licensed by Orbbec under the agreement shown during setup.";
const EULA_PREFACE: &str = "Orbbec camera support is Orbbec's software, not OdysseyArm's. It is installed only if you keep \"Orbbec camera support\" ticked on the next page, and it is yours to use under Orbbec's End User License Agreement, which follows. You can leave the feature out and add it later from Windows Settings > Apps > Odyssey > Modify.";

const USER_AGENT: &str = "odyssey-msi-build";
const FETCH_TIMEOUT: Duration = Duration::from_secs(300);
/// The SDK archive is ~60 MB, past ureq's 10 MB default body limit.
const MAX_DOWNLOAD: u64 = 1 << 30;

const ONLINE_FRAGMENT: &str = r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by cargo xtask desktop prepare-orbbec (online variant). Do not edit. -->
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
    <Fragment>
        <!-- The template always references this feature. Online installers carry no SDK, so
             it is empty and never offered; the app downloads the SDK itself. -->
        <Feature Id="OrbbecSdk" Title="Orbbec camera support" Level="0" Display="hidden" />
    </Fragment>
</Wix>
"#;

/// The SDK this build is tested with. The app reads the same file.
#[derive(Deserialize)]
struct Pin {
    version: String,
    eula: Download,
    windows_x64: Archive,
}

#[derive(Deserialize)]
struct Download {
    url: String,
    sha256: String,
}

#[derive(Deserialize)]
struct Archive {
    url: String,
    sha256: String,
    /// Paths inside the archive.
    files: Vec<String>,
}

pub(super) fn default_stage() -> PathBuf {
    cmd::root().join(DIR).join("target").join("orbbec-stage")
}

/// Returns the absolute stage directory.
pub(super) fn prepare(
    variant: Variant,
    stage: &Path,
    archive: Option<&Path>,
    eula: Option<&Path>,
) -> eros::Result<PathBuf> {
    let absolute =
        std::path::absolute(stage).with_context(|| format!("resolving {}", stage.display()))?;
    // shortcut: `..` is folded lexically and symlinks are kept; resolve them if a
    // stage under a symlink ever needs canonical Source paths.
    let mut stage = PathBuf::new();
    for component in absolute.components() {
        if let Component::ParentDir = component {
            stage.pop();
        } else {
            stage.push(component);
        }
    }
    if stage.exists() {
        fs::remove_dir_all(&stage).with_context(|| format!("removing {}", stage.display()))?;
    }
    fs::create_dir_all(&stage).with_context(|| format!("creating {}", stage.display()))?;

    let fragment = stage.join("orbbec.wxs");
    let Variant::Full = variant else {
        write_text(&fragment, ONLINE_FRAGMENT)?;
        println!("online: wrote {}", fragment.display());
        return Ok(stage);
    };

    let pin_file = cmd::root().join(DIR).join(PIN_FILE);
    let pin_text =
        fs::read_to_string(&pin_file).with_context(|| format!("reading {}", pin_file.display()))?;
    let pin: Pin = serde_json::from_str(&pin_text)
        .with_context(|| format!("parsing {}", pin_file.display()))?;

    let archive = match archive {
        Some(path) => read(path)?,
        None => fetch(&pin.windows_x64.url)?,
    };
    verify(&archive, &pin.windows_x64.sha256, "the SDK archive")?;
    let eula = match eula {
        Some(path) => read(path)?,
        None => fetch(&pin.eula.url)?,
    };
    verify(&eula, &pin.eula.sha256, "the Orbbec EULA")?;

    let sdk = stage.join("orbbec-sdk");
    let mut installed = extract(&archive, &pin.windows_x64.files, &sdk)?;
    // The EULA travels with the SDK, and its text is the installer's licence page.
    let eula_txt = sdk.join("EULA.txt");
    fs::write(&eula_txt, &eula).with_context(|| format!("writing {}", eula_txt.display()))?;
    installed.push("EULA.txt".to_owned());
    let text = String::from_utf8(eula).context("the Orbbec EULA is not UTF-8")?;
    write_text(&stage.join("EULA.rtf"), &eula_rtf(&text))?;
    write_text(&fragment, &full_fragment(&stage, &installed)?)?;
    println!(
        "full: SDK {}, {} files, staged in {}",
        pin.version,
        installed.len(),
        stage.display()
    );
    Ok(stage)
}

pub(super) fn read(path: &Path) -> eros::Result<Vec<u8>> {
    Ok(fs::read(path).with_context(|| format!("reading {}", path.display()))?)
}

fn fetch(url: &str) -> eros::Result<Vec<u8>> {
    let mut response = ureq::get(url)
        .config()
        .timeout_connect(Some(FETCH_TIMEOUT))
        .timeout_recv_response(Some(FETCH_TIMEOUT))
        .build()
        .header("User-Agent", USER_AGENT)
        .call()
        .with_context(|| format!("downloading {url}"))?;
    Ok(response
        .body_mut()
        .with_config()
        .limit(MAX_DOWNLOAD)
        .read_to_vec()
        .with_context(|| format!("downloading {url}"))?)
}

/// Native line endings, so the staged text files match what a text-mode writer
/// produces on the build machine.
fn write_text(path: &Path, text: &str) -> eros::Result<()> {
    let text = if cfg!(windows) {
        text.replace('\n', "\r\n")
    } else {
        text.to_owned()
    };
    Ok(fs::write(path, text).with_context(|| format!("writing {}", path.display()))?)
}

pub(super) fn verify(data: &[u8], expected: &str, what: &str) -> eros::Result<()> {
    let actual = hex::encode(Sha256::digest(data));
    if !actual.eq_ignore_ascii_case(expected) {
        eros::bail!("{what}: expected sha256 {expected}, got {actual}");
    }
    Ok(())
}

/// Where an archive file lands inside the SDK directory: bin/ is dropped, so
/// OrbbecSDK.dll lands beside its extensions/ folder.
fn install_path(archive_path: &str) -> &str {
    archive_path.strip_prefix("bin/").unwrap_or(archive_path)
}

fn native_path(base: &Path, relative: &str) -> PathBuf {
    let mut path = base.to_path_buf();
    for part in relative.split('/') {
        path.push(part);
    }
    path
}

/// Writes the listed files under `dest` and returns their install paths.
fn extract(archive: &[u8], files: &[String], dest: &Path) -> eros::Result<Vec<String>> {
    let mut zip = zip::ZipArchive::new(Cursor::new(archive)).context("opening the SDK archive")?;
    // Archives made on Windows store `\` separators.
    let mut index = HashMap::new();
    for name in zip.file_names() {
        index.insert(name.replace('\\', "/"), name.to_owned());
    }
    let mut missing = Vec::new();
    for file in files {
        if !index.contains_key(file) {
            missing.push(file.as_str());
        }
    }
    if !missing.is_empty() {
        eros::bail!("the SDK archive does not contain: {}", missing.join(", "));
    }

    let mut installed = Vec::new();
    for file in files {
        let path = install_path(file);
        let target = native_path(dest, path);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent).with_context(|| format!("creating {}", parent.display()))?;
        }
        let mut bytes = Vec::new();
        zip.by_name(&index[file])
            .with_context(|| format!("opening {file} in the SDK archive"))?
            .read_to_end(&mut bytes)
            .with_context(|| format!("unpacking {file}"))?;
        fs::write(&target, bytes).with_context(|| format!("writing {}", target.display()))?;
        installed.push(path.to_owned());
    }
    Ok(installed)
}

fn rtf_escape(text: &str) -> String {
    let mut out = String::new();
    for ch in text.replace("\r\n", "\n").chars() {
        match ch {
            '\\' | '{' | '}' => {
                out.push('\\');
                out.push(ch);
            }
            '\n' => out.push_str("\\par\n"),
            _ if ch.is_ascii() => out.push(ch),
            _ => {
                // RTF takes UTF-16 code units as signed 16-bit numbers, `?` as the fallback.
                let mut units = [0; 2];
                for unit in ch.encode_utf16(&mut units) {
                    write!(out, "\\u{}?", *unit as i16).expect("writing to String cannot fail");
                }
            }
        }
    }
    out
}

fn eula_rtf(eula: &str) -> String {
    format!(
        "{{\\rtf1\\ansi\\deff0{{\\fonttbl{{\\f0\\fswiss Segoe UI;}}}}\\f0\\fs18 {}\\par\\par\n{}}}",
        rtf_escape(EULA_PREFACE),
        rtf_escape(eula)
    )
}

/// A `WiX` identifier: letters, digits, `_` and `.`, at most [`WIX_ID_MAX`] characters.
fn wix_id(prefix: &str, path: &str) -> String {
    let cleaned: String = path
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() || ch == '_' {
                ch
            } else {
                '_'
            }
        })
        .collect();
    let candidate = format!("{prefix}_{cleaned}");
    if candidate.len() <= WIX_ID_MAX {
        return candidate;
    }
    let hash = hex::encode(Sha1::digest(path.as_bytes()));
    format!("{prefix}_{}_{}", &cleaned[..40], &hash[..20])
}

/// A name-based (version 5) UUID of `path` in [`GUID_NAMESPACE`], upper case.
fn component_guid(path: &str) -> String {
    let namespace = hex::decode(GUID_NAMESPACE.replace('-', "")).expect("GUID_NAMESPACE is a UUID");
    let mut hasher = Sha1::new();
    hasher.update(&namespace);
    hasher.update(path.as_bytes());
    let digest = hasher.finalize();
    let mut bytes: [u8; 16] = digest[..16].try_into().expect("SHA-1 is 20 bytes");
    bytes[6] = (bytes[6] & 0x0f) | 0x50;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    let hex = hex::encode_upper(bytes);
    format!(
        "{}-{}-{}-{}-{}",
        &hex[..8],
        &hex[8..12],
        &hex[12..16],
        &hex[16..20],
        &hex[20..]
    )
}

/// An XML attribute value with its quotes, as Python's `xml.sax.saxutils.quoteattr`.
fn quote_attr(value: &str) -> String {
    let escaped = value
        .replace('&', "&amp;")
        .replace('>', "&gt;")
        .replace('<', "&lt;")
        .replace('\n', "&#10;")
        .replace('\r', "&#13;")
        .replace('\t', "&#9;");
    if !escaped.contains('"') {
        return format!("\"{escaped}\"");
    }
    if escaped.contains('\'') {
        return format!("\"{}\"", escaped.replace('"', "&quot;"));
    }
    format!("'{escaped}'")
}

#[derive(Default)]
struct DirTree(BTreeMap<String, Self>);

fn parent_dir(path: &str) -> &str {
    path.rsplit_once('/').map_or("", |(dir, _)| dir)
}

fn full_fragment(stage: &Path, installed: &[String]) -> eros::Result<String> {
    let sdk = stage.join("orbbec-sdk");
    let mut ids = Vec::new();
    for prefix in ["C", "F"] {
        for path in installed {
            ids.push(wix_id(prefix, path));
        }
    }
    if ids.iter().collect::<BTreeSet<_>>().len() != ids.len() {
        eros::bail!("two SDK files map to the same WiX id; make wix_id tell them apart");
    }

    let mut tree = DirTree::default();
    for path in installed {
        let mut node = &mut tree;
        for part in parent_dir(path).split('/').filter(|part| !part.is_empty()) {
            node = node.0.entry(part.to_owned()).or_default();
        }
    }

    let root = directory_xml(&sdk, installed, "orbbec-sdk", &tree, "orbbec-sdk", 3);
    let mut sorted = installed.to_vec();
    sorted.sort();
    let mut refs = String::new();
    for path in &sorted {
        writeln!(
            refs,
            "            <ComponentRef Id={} />",
            quote_attr(&wix_id("C", path))
        )
        .expect("writing to String cannot fail");
    }
    let title = quote_attr(FEATURE_TITLE);
    let description = quote_attr(FEATURE_DESCRIPTION);
    Ok(format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by cargo xtask desktop prepare-orbbec (full variant). Do not edit. -->
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
    <Fragment>
        <DirectoryRef Id="INSTALLDIR">
{root}        </DirectoryRef>
    </Fragment>
    <Fragment>
        <ComponentGroup Id="OrbbecSdkFiles">
{refs}        </ComponentGroup>
    </Fragment>
    <Fragment>
        <!-- On by default (Level 1): an upgrade offers it again, ticked, so someone who has
             it keeps it. Untick it, or use Modify later, to leave it out. -->
        <Feature
            Id="OrbbecSdk"
            Title={title}
            Description={description}
            Level="1"
            AllowAdvertise="no">
            <ComponentGroupRef Id="OrbbecSdkFiles" />
        </Feature>
    </Fragment>
</Wix>
"#
    ))
}

/// `rel` is the directory's path from the stage, starting with `orbbec-sdk`.
fn directory_xml(
    sdk: &Path,
    installed: &[String],
    name: &str,
    tree: &DirTree,
    rel: &str,
    indent: usize,
) -> String {
    let pad = "    ".repeat(indent);
    let inside_sdk = rel.split_once('/').map_or("", |(_, rest)| rest);
    let mut files_here: Vec<&String> = installed
        .iter()
        .filter(|path| parent_dir(path) == inside_sdk)
        .collect();
    files_here.sort();
    let mut xml = format!(
        "{pad}<Directory Id={} Name={}>\n",
        quote_attr(&wix_id("D", rel)),
        quote_attr(name)
    );
    for path in files_here {
        xml.push_str(&component_xml(sdk, path, indent + 1));
    }
    for (child, subtree) in &tree.0 {
        xml.push_str(&directory_xml(
            sdk,
            installed,
            child,
            subtree,
            &format!("{rel}/{child}"),
            indent + 1,
        ));
    }
    writeln!(xml, "{pad}</Directory>").expect("writing to String cannot fail");
    xml
}

fn component_xml(sdk: &Path, path: &str, indent: usize) -> String {
    let pad = "    ".repeat(indent);
    let file_name = path.rsplit('/').next().unwrap_or(path);
    let source = native_path(sdk, path);
    format!(
        "{pad}<Component Id={} Guid=\"{}\">\n\
         {pad}    <File Id={} Name={} Source={} KeyPath=\"yes\" />\n\
         {pad}</Component>\n",
        quote_attr(&wix_id("C", path)),
        component_guid(path),
        quote_attr(&wix_id("F", path)),
        quote_attr(file_name),
        quote_attr(&source.to_string_lossy()),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn strings(paths: &[&str]) -> Vec<String> {
        paths.iter().map(|path| (*path).to_owned()).collect()
    }

    // Reference outputs are prepare_orbbec.py's, byte for byte apart from the generated-by line.
    #[cfg(unix)]
    #[test]
    fn full_fragment_matches_reference() {
        let installed = strings(&[
            "OrbbecSDK.dll",
            "extensions/depthengine/depthengine.dll",
            "extensions/filters/FilterProcessor.dll",
            "licenses/live555/COPYING.LESSER",
            "licenses/a very long directory name that overflows/and-a-file-name-that-is-long.txt",
            "licenses/it's \"odd\" & <x>.txt",
            "EULA.txt",
        ]);
        let fragment = full_fragment(Path::new("/stage"), &installed).expect("ids are unique");
        assert_eq!(fragment, include_str!("../../testdata/orbbec-fragment.wxs"));
    }

    #[test]
    fn eula_rtf_matches_reference() {
        assert_eq!(
            eula_rtf("A {b} \\c\r\nd\u{e9} \u{1F600}\rend\n"),
            include_str!("../../testdata/orbbec-eula.rtf")
        );
    }

    #[test]
    fn component_guid_is_uuid5_in_the_fixed_namespace() {
        assert_eq!(
            component_guid("OrbbecSDK.dll"),
            "07FE31E5-6390-5405-AB11-E403D43496AB"
        );
    }

    #[test]
    fn wix_id_hashes_only_past_the_limit() {
        let fits = "x".repeat(WIX_ID_MAX - 2);
        assert_eq!(wix_id("C", &fits), format!("C_{fits}"));
        assert_eq!(
            wix_id("C", &"x".repeat(WIX_ID_MAX - 1)),
            format!("C_{}_fd1ee778e79ae344f333", "x".repeat(40))
        );
        assert_eq!(wix_id("F", "\u{e9}/\u{fc}-\u{df}"), "F______");
    }

    #[test]
    fn quote_attr_picks_quotes_like_saxutils() {
        assert_eq!(quote_attr("plain"), "\"plain\"");
        assert_eq!(quote_attr("a\"b"), "'a\"b'");
        assert_eq!(quote_attr("a\"b'c"), "\"a&quot;b'c\"");
        assert_eq!(
            quote_attr("x\ty\nz\r<&>"),
            "\"x&#9;y&#10;z&#13;&lt;&amp;&gt;\""
        );
    }

    #[test]
    fn verify_compares_sha256_case_insensitively() {
        let empty = "E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855";
        verify(b"", empty, "empty").expect("matching SHA-256 is accepted");
        verify(b"x", empty, "x").expect_err("mismatched SHA-256 is rejected");
    }

    #[test]
    fn duplicate_ids_are_refused() {
        let installed = strings(&["a-b.dll", "a_b.dll"]);
        full_fragment(Path::new("/stage"), &installed)
            .expect_err("duplicate WiX identifiers are refused");
    }

    #[test]
    fn pinned_sdk_stages_a_valid_fragment() {
        let pin: Pin =
            serde_json::from_str(include_str!("../../../odyssey-desktop/orbbec-sdk.json"))
                .expect("orbbec-sdk.json parses");
        let mut installed: Vec<String> = pin
            .windows_x64
            .files
            .iter()
            .map(|file| install_path(file).to_owned())
            .collect();
        installed.push("EULA.txt".to_owned());
        full_fragment(Path::new("/stage"), &installed).expect("unique identifiers are accepted");
        assert_eq!(pin.eula.sha256.len(), 64);
        assert_eq!(pin.windows_x64.sha256.len(), 64);
    }

    fn zip_of(entries: &[(&str, &[u8])]) -> Vec<u8> {
        let mut writer = zip::ZipWriter::new(Cursor::new(Vec::new()));
        for (name, data) in entries {
            writer
                .start_file(*name, zip::write::SimpleFileOptions::default())
                .expect("in-memory zip accepts the entry");
            std::io::Write::write_all(&mut writer, data).expect("in-memory write");
        }
        writer
            .finish()
            .expect("in-memory zip finishes")
            .into_inner()
    }

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("xtask-orbbec-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn extract_drops_bin_and_reads_windows_separators() {
        let archive = zip_of(&[
            ("bin\\OrbbecSDK.dll", b"dll"),
            ("bin/extensions/x/y.dll", b"ext"),
            ("LICENSE.txt", b"license"),
            ("unlisted.txt", b"no"),
        ]);
        let dest = scratch("extract");
        let files = strings(&["bin/OrbbecSDK.dll", "bin/extensions/x/y.dll", "LICENSE.txt"]);
        let installed = extract(&archive, &files, &dest).expect("all files present");
        assert_eq!(
            installed,
            strings(&["OrbbecSDK.dll", "extensions/x/y.dll", "LICENSE.txt"])
        );
        assert_eq!(
            fs::read(dest.join("OrbbecSDK.dll")).ok(),
            Some(b"dll".to_vec())
        );
        assert_eq!(
            fs::read(dest.join("extensions").join("x").join("y.dll")).ok(),
            Some(b"ext".to_vec())
        );
        assert!(!dest.join("unlisted.txt").exists());
        fs::remove_dir_all(&dest).expect("scratch dir removable");
    }

    #[test]
    fn extract_names_every_missing_file() {
        let archive = zip_of(&[("LICENSE.txt", b"license")]);
        let dest = scratch("missing");
        let files = strings(&["bin/OrbbecSDK.dll", "LICENSE.txt", "licenses/x"]);
        let error = extract(&archive, &files, &dest).expect_err("files are missing");
        let message = format!("{error:?}");
        assert!(
            message.contains("bin/OrbbecSDK.dll, licenses/x"),
            "{message}"
        );
        assert!(!dest.exists());
    }
}
