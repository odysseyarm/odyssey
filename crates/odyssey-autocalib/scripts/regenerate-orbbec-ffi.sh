#!/usr/bin/env bash
# Regenerates src/orbbec/ffi.rs, the checked-in function table for OrbbecSDK v2.
#
# usage: regenerate-orbbec-ffi.sh <SDK include dir>
#
# <SDK include dir> is the `include/` directory of the official OrbbecSDK v2.10.6
# release archive (or of a CMake install of that tag). The raw source tree is not
# enough: `libobsensor/h/Export.h` only exists after the SDK's CMake step.
#
# Needs, on the machine that runs it and nowhere in the normal build:
#   - bindgen-cli 0.72.x   cargo install bindgen-cli --version 0.72.1 --locked
#   - libclang             (set LIBCLANG_PATH if bindgen cannot find it)
#   - rustfmt
#
# What gets emitted follows the backend source, so adding an SDK call to
# src/orbbec.rs or src/orbbec/runtime.rs and rerunning this script is the whole
# procedure:
#   - functions: every `ob_*` identifier those files mention
#   - constants: every `ffi::OB*` path those files mention
#   - types:     every `ffi::ob_*` path those files mention, plus whatever the
#                emitted functions' signatures reach
# bindgen cannot select single enum variants, so it emits each reached enum in
# full and this script then drops the constants nothing references.
set -euo pipefail

if [[ $# -ne 1 || ! -f "$1/libobsensor/ObSensor.h" ]]; then
    echo "usage: $0 <OrbbecSDK v2.10.6 include dir containing libobsensor/ObSensor.h>" >&2
    exit 2
fi
include=$(cd "$1" && pwd)

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
src="$here/../src"
out="$src/orbbec/ffi.rs"
sources=("$src/orbbec.rs" "$src/orbbec/runtime.rs")

functions=$(grep -ohE '\bob_[a-z0-9_]+' "${sources[@]}" | sort -u | paste -sd'|')
constants=$(grep -ohE 'ffi::OB[A-Za-z0-9_]+' "${sources[@]}" | sed 's/^ffi:://' | sort -u | paste -sd'|')
types=$(grep -ohE 'ffi::ob_[a-z0-9_]+' "${sources[@]}" | sed 's/^ffi:://' | sort -u | paste -sd'|')

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

bindgen "$include/libobsensor/ObSensor.h" \
    --output "$tmp" \
    --formatter rustfmt \
    --no-layout-tests \
    --no-doc-comments \
    --dynamic-loading OrbbecSdk \
    --dynamic-link-require-all \
    --allowlist-function "^($functions)\$" \
    --allowlist-type "^($types)\$" \
    --raw-line '// Function table for the OrbbecSDK v2 C API, version 2.10.6.' \
    --raw-line '//' \
    --raw-line '// Generated by scripts/regenerate-orbbec-ffi.sh with bindgen 0.72.1. Do not edit;' \
    --raw-line '// change the script or the backend sources and run it again.' \
    --raw-line '#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]' \
    -- "-I$include"

awk -v keep="^($constants)\$" '
    skipping { if ($0 ~ /;$/) skipping = 0; next }
    /^pub const OB[A-Za-z0-9_]+:/ {
        name = $3
        sub(/:$/, "", name)
        if (name !~ keep) {
            # rustfmt wraps long constants onto a second line.
            if ($0 !~ /;$/) skipping = 1
            next
        }
    }
    { print }
' "$tmp" >"$out"

echo "wrote $out"
